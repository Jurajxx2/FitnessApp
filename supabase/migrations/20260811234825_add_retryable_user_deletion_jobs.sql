-- Owner changes already hold the content row lock before this trigger runs.
-- Direct ownership is carried by `user_id` on both fenced tables and, on
-- public.workouts only, by `owner_user_id`; both columns cascade from
-- auth.users, so both are deletion-relevant. public.meal_plans has no
-- `owner_user_id` column: `to_jsonb(...)->>'owner_user_id'` yields NULL there
-- and the value is discarded as "not present", so the same function serves both
-- triggers.
--
-- Only the NEW ownership values are locked and tested. The OLD values are
-- deliberately NOT locked: a transfer that moves ownership AWAY from a target
-- only makes that target more deletable, so losing that serialization cannot
-- create shared content after preflight. Under MVCC the preflight either sees
-- the pre-transfer row and conservatively flags manual review, or the
-- post-transfer row which no longer references the target; both are safe. Any
-- transfer TOWARD a target is a NEW value and is still locked and tested.
-- Locking the OLD keys would put an ordinary ownership handover — including the
-- remediation this migration's runbook publishes — onto the outgoing athlete's
-- deletion key, where an operator transaction already holding that athlete's
-- profiles row lock could deadlock against admin_begin_user_deletion.
CREATE OR REPLACE FUNCTION private.lock_deletion_direct_content_owner()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_new JSONB := to_jsonb(NEW);
  v_new_user_id UUID := (v_new->>'user_id')::UUID;
  v_new_owner_user_id UUID := (v_new->>'owner_user_id')::UUID;
  v_owner_ids UUID[];
  v_owner_id UUID;
BEGIN
  SELECT array_agg(deduplicated.owner_id ORDER BY deduplicated.owner_id::TEXT)
  INTO v_owner_ids
  FROM (
    SELECT DISTINCT owner_candidate.owner_id
    FROM (
      VALUES
        (v_new_user_id::UUID),
        (v_new_owner_user_id::UUID)
    ) AS owner_candidate(owner_id)
    WHERE owner_candidate.owner_id IS NOT NULL
  ) AS deduplicated;

  IF v_owner_ids IS NOT NULL THEN
    FOREACH v_owner_id IN ARRAY v_owner_ids LOOP
      PERFORM pg_advisory_xact_lock_shared(
        hashtextextended(v_owner_id::TEXT, 24001)
      );
    END LOOP;
  END IF;

  IF EXISTS (
       SELECT 1
       FROM public.user_deletion_jobs job
       WHERE job.status <> 'completed'
         AND (
           job.target_user_id = v_new_user_id
           OR job.target_user_id = v_new_owner_user_id
         )
     ) THEN
    RAISE EXCEPTION 'Direct content owner has an active deletion job'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.lock_deletion_direct_content_owner() FROM PUBLIC;

