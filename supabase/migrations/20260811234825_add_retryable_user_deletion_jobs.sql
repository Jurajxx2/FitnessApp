-- Durable, retryable deletion orchestration. This migration intentionally does
-- not schedule or invoke the worker: deploying admin-manage-user is a separate
-- rollout gate.

CREATE TABLE public.user_deletion_jobs (
  -- A target has exactly one lifetime deletion job, so using the target UUID as
  -- the job UUID lets the audited Edge handler identify it before the atomic
  -- begin RPC mutates anything.
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  target_user_id UUID NOT NULL,
  requested_by UUID NOT NULL,
  status TEXT NOT NULL DEFAULT 'requested'
    CHECK (status IN (
      'requested',
      'cleaning_storage',
      'deleting_auth',
      'retryable_error',
      'manual_review',
      'completed'
    )),
  resume_status TEXT
    CHECK (resume_status IS NULL OR resume_status IN ('cleaning_storage', 'deleting_auth')),
  lease_token UUID,
  lease_expires_at TIMESTAMPTZ,
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  removed_object_count BIGINT NOT NULL DEFAULT 0 CHECK (removed_object_count >= 0),
  last_error_code TEXT,
  last_error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  UNIQUE (target_user_id),
  CHECK ((lease_token IS NULL) = (lease_expires_at IS NULL)),
  CHECK ((status = 'completed') = (completed_at IS NOT NULL)),
  CHECK (status = 'retryable_error' OR resume_status IS NULL)
);

CREATE TABLE public.user_deletion_bucket_progress (
  job_id UUID NOT NULL REFERENCES public.user_deletion_jobs(id) ON DELETE CASCADE,
  bucket_id TEXT NOT NULL
    CHECK (bucket_id IN ('chat-images', 'check-in-photos', 'meal-photos')),
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'cleaning', 'clean')),
  removed_object_count BIGINT NOT NULL DEFAULT 0 CHECK (removed_object_count >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (job_id, bucket_id)
);

CREATE TABLE public.user_deletion_prefix_work (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id UUID NOT NULL REFERENCES public.user_deletion_jobs(id) ON DELETE CASCADE,
  bucket_id TEXT NOT NULL,
