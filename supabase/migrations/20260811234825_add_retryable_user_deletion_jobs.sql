  ON storage.objects AS RESTRICTIVE FOR UPDATE TO authenticated
  USING (
    bucket_id NOT IN ('chat-images', 'check-in-photos', 'meal-photos')
    OR private.lock_deletion_storage_write(name, owner_id)
  )
  WITH CHECK (
    bucket_id NOT IN ('chat-images', 'check-in-photos', 'meal-photos')
