-- auth.users -> profiles (CASCADE) -> workout_feedback.coach_id (CASCADE)
-- destroys coach feedback the target authored on ANOTHER athlete's training
-- log. Fence new authored rows the same way directly owned content is fenced.
--
-- Exactly one key is locked and tested: NEW.coach_id. Rejection depends solely
-- on that column, so this is a single-lock site and ordering is trivial.
--
-- `NEW.user_id` is deliberately NOT locked. It is the athlete key — the normal
-- deletion target — so locking it would put every ordinary admin feedback write
-- onto the deletion keyspace, where a transaction already holding that
-- athlete's profiles row lock could deadlock against admin_begin_user_deletion
-- (which takes the exclusive advisory lock first and the profile row lock
-- second). `OLD.coach_id` is not locked either: moving authorship AWAY from a
-- target only makes that target more deletable, so losing that serialization
-- cannot create authored content after preflight. Under MVCC the preflight sees
-- either the pre-change row (flags manual review — conservative and safe) or the
-- post-change row (no longer authored by the target — also safe). Authorship
-- moved TOWARD a coach is a NEW value and is still locked and tested.
CREATE OR REPLACE FUNCTION private.lock_deletion_feedback_author()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM pg_advisory_xact_lock_shared(
    hashtextextended(NEW.coach_id::TEXT, 24001)
  );

  IF NEW.coach_id <> NEW.user_id
     AND EXISTS (
       SELECT 1 FROM public.user_deletion_jobs job
       WHERE job.target_user_id = NEW.coach_id
         AND job.status <> 'completed'
     ) THEN
    RAISE EXCEPTION 'Feedback author has an active deletion job'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.lock_deletion_feedback_author() FROM PUBLIC;

CREATE TRIGGER lock_workout_feedback_during_deletion
BEFORE INSERT OR UPDATE OF coach_id, user_id ON public.workout_feedback
FOR EACH ROW EXECUTE FUNCTION private.lock_deletion_feedback_author();

-- Auth access tokens can remain valid until expiry after user deletion. These
-- restrictive policies make the profile block effective for the three
-- user-owned buckets before cleanup starts and keep a stale token from
