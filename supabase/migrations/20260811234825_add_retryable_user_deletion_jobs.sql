-- Storage writes take a transaction-scoped shared lock for the user identified
-- by the managed prefix (falling back to owner_id). The deletion begin RPC
-- takes the matching exclusive lock before blocking the profile. Therefore an
-- upload already in progress commits before cleanup starts, while a later
-- upload waits and then observes the blocked/missing profile.
CREATE OR REPLACE FUNCTION private.lock_deletion_storage_write(
  p_name TEXT,
  p_owner_id TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_prefix TEXT := split_part(COALESCE(p_name, ''), '/', 1);
  v_actor_user_id UUID := auth.uid();
  v_target_user_id UUID;
  v_unblocked BOOLEAN;
BEGIN
  IF v_prefix ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
    v_target_user_id := v_prefix::UUID;
  ELSIF COALESCE(p_owner_id, '') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
    v_target_user_id := p_owner_id::UUID;
  ELSE
    v_target_user_id := auth.uid();
  END IF;

  IF v_actor_user_id IS NULL OR v_target_user_id IS NULL THEN
    RETURN false;
  END IF;
  IF v_target_user_id <> v_actor_user_id
     AND NOT public.get_is_admin() THEN
    RETURN false;
  END IF;

  PERFORM pg_advisory_xact_lock_shared(
    hashtextextended(v_target_user_id::TEXT, 24001)
  );

  SELECT NOT profile.is_blocked INTO v_unblocked
  FROM public.profiles profile
  WHERE profile.id = v_target_user_id;

  RETURN COALESCE(v_unblocked, false);
END;
$$;

REVOKE ALL ON FUNCTION private.lock_deletion_storage_write(TEXT, TEXT)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION private.lock_deletion_storage_write(TEXT, TEXT)
  TO authenticated;

-- Deadlock-freedom invariants for this migration. Every advisory lock below
-- lives in the single `hashtextextended(<uuid>::TEXT, 24001)` keyspace, and:
--
--   (a) Exactly one EXCLUSIVE advisory lock exists in that keyspace: the first
--       statement of public.admin_begin_user_deletion. It is taken before that
--       function acquires any row lock, so it can never be reached while
--       already holding one.
--   (b) Every other lock here is SHARED, so the fences never conflict with one
--       another and their relative order is not load-bearing between them.
--       They are still taken in ascending UUID-text order at each multi-lock
--       site so that a future exclusive locker cannot invert against them.
--   (c) Every fence locks exactly the keys its rejection predicate tests, and
--       nothing else. Locking a key that is not tested would drag ordinary
--       write paths onto the deletion keyspace for no safety benefit and let
--       them deadlock against (a) via the profile row lock. This holds for all
--       three fences: lock_deletion_direct_content_owner locks and tests only
--       the NEW ownership values, lock_deletion_feedback_author locks and tests
--       only NEW.coach_id, and lock_deletion_content_assignment locks exactly
--       the direct-owner set that its predicate then tests.
--
-- This does NOT eliminate the deadlock class. lock_deletion_content_assignment
-- must lock deletion-target keys, because those are precisely the keys it
-- tests. So a transaction that takes a profiles(T) row lock and then performs a
-- fenced assignment write against content owned by T, in the SAME transaction,
-- can still cycle with admin_begin_user_deletion and get 40P01. Operators must
-- keep profile writes and fenced content writes in separate transactions; a
-- 40P01 is retryable and the operation should simply be repeated.

-- Cross-user assignments take the same shared target lock. This prevents an
-- admin save from making directly owned content shared after deletion
-- preflight but before the owner's profile is removed. A workout is directly
-- owned through either `user_id` or `owner_user_id`; both cascade from the
-- owner, so both must be fenced.
CREATE OR REPLACE FUNCTION private.lock_deletion_content_assignment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_row JSONB := to_jsonb(NEW);
  v_content_id UUID;
  v_assigned_user_id UUID := (v_row->>'user_id')::UUID;
  v_owner_candidates UUID[];
  v_direct_owner_ids UUID[];
  v_direct_owner_id UUID;
BEGIN
  IF TG_TABLE_NAME = 'user_workouts' THEN
    v_content_id := (v_row->>'workout_id')::UUID;
    SELECT ARRAY[workout.user_id, workout.owner_user_id]
    INTO v_owner_candidates
    FROM public.workouts workout
    WHERE workout.id = v_content_id
    FOR SHARE;
  ELSIF TG_TABLE_NAME = 'user_meal_plans' THEN
    v_content_id := (v_row->>'meal_plan_id')::UUID;
    SELECT ARRAY[plan.user_id]
    INTO v_owner_candidates
    FROM public.meal_plans plan
    WHERE plan.id = v_content_id
    FOR SHARE;
  ELSE
    RAISE EXCEPTION 'Unsupported deletion assignment table' USING ERRCODE = '22023';
  END IF;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Assignment parent is not yet visible'
      USING ERRCODE = '40001';
  END IF;

  -- Deduplicate and sort ascending before locking so a workout owned through
  -- both columns locks once and multi-owner rows never invert lock order.
  SELECT array_agg(deduplicated.owner_id ORDER BY deduplicated.owner_id::TEXT)
  INTO v_direct_owner_ids
  FROM (
    SELECT DISTINCT owner_candidate.owner_id
    FROM unnest(v_owner_candidates) AS owner_candidate(owner_id)
    WHERE owner_candidate.owner_id IS NOT NULL
  ) AS deduplicated;

  IF v_direct_owner_ids IS NULL THEN
    RETURN NEW;
  END IF;

  FOREACH v_direct_owner_id IN ARRAY v_direct_owner_ids LOOP
    PERFORM pg_advisory_xact_lock_shared(
      hashtextextended(v_direct_owner_id::TEXT, 24001)
    );
  END LOOP;

  IF EXISTS (
       SELECT 1
       FROM unnest(v_direct_owner_ids) AS direct_owner(owner_id)
       JOIN public.user_deletion_jobs job
         ON job.target_user_id = direct_owner.owner_id
       WHERE direct_owner.owner_id <> v_assigned_user_id
         AND job.status <> 'completed'
     ) THEN
    RAISE EXCEPTION 'Direct content owner has an active deletion job'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.lock_deletion_content_assignment() FROM PUBLIC;

