  ON storage.objects AS RESTRICTIVE FOR DELETE TO authenticated
  USING (
    bucket_id NOT IN ('chat-images', 'check-in-photos', 'meal-photos')
    OR (SELECT public.get_is_admin())
    OR (SELECT private.is_current_user_unblocked())
  );

-- Service-role-only, invoker-rights RPC. The service role already owns the
-- required table privileges, so no exposed SECURITY DEFINER function is needed.
CREATE OR REPLACE FUNCTION public.admin_begin_user_deletion(
  p_target_user_id UUID,
  p_requested_by UUID
)
RETURNS public.user_deletion_jobs
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_job public.user_deletion_jobs;
  v_target public.profiles;
  v_off_prefix_count BIGINT;
  v_cross_user_request_count BIGINT;
  v_shared_direct_content_count BIGINT;
  v_shared_authored_content_count BIGINT;
BEGIN
  PERFORM pg_advisory_xact_lock(
    hashtextextended(p_target_user_id::TEXT, 24001)
  );

  SELECT * INTO v_job
  FROM public.user_deletion_jobs
  WHERE target_user_id = p_target_user_id
  FOR UPDATE;

  IF FOUND THEN
    IF v_job.status = 'retryable_error' THEN
      UPDATE public.user_deletion_jobs
      SET status = COALESCE(resume_status, 'cleaning_storage'),
          resume_status = NULL,
          last_error_code = NULL,
          last_error_message = NULL,
          lease_token = NULL,
          lease_expires_at = NULL
      WHERE id = v_job.id
      RETURNING * INTO v_job;
    END IF;
    RETURN v_job;
  END IF;

  SELECT * INTO v_target
  FROM public.profiles
  WHERE id = p_target_user_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'User not found' USING ERRCODE = 'P0002';
  END IF;
  IF v_target.is_admin THEN
    RAISE EXCEPTION 'Existing admin accounts cannot be deleted here' USING ERRCODE = '23514';
  END IF;
  IF p_target_user_id = p_requested_by THEN
    RAISE EXCEPTION 'Administrators cannot delete their own account' USING ERRCODE = '23514';
  END IF;

  -- Block before any cleanup work so a partially deleted athlete cannot keep
  -- creating rows or objects while a retry is pending.
  UPDATE public.profiles SET is_blocked = true WHERE id = p_target_user_id;

  SELECT count(*) INTO v_off_prefix_count
  FROM storage.objects
  WHERE bucket_id IN ('chat-images', 'check-in-photos', 'meal-photos')
    AND owner_id = p_target_user_id::text
    AND name <> p_target_user_id::text
    AND name NOT LIKE p_target_user_id::text || '/%';

  -- requested_by is intentionally retained as immutable audit evidence. A
  -- cross-user generation request therefore needs an operator decision before
  -- the target Auth row can be removed.
  SELECT count(*) INTO v_cross_user_request_count
  FROM public.meal_plan_generation_requests
  WHERE requested_by = p_target_user_id
    AND user_id <> p_target_user_id;

  -- A workout is directly owned through either `user_id` or `owner_user_id`;
  -- both cascade from auth.users. One predicate over public.workouts counts a
  -- workout owned through both columns exactly once. A workout is shared when
  -- another user holds an assignment OR when the two ownership columns point
  -- at different users: this migration turns workouts_user_id_fkey into
  -- ON DELETE CASCADE, so a divergently owned workout would otherwise be
  -- destroyed for the other owner without any operator signal.
  -- public.meal_plans has no owner column, so its branch stays keyed on
  -- `plan.user_id`.
  SELECT
    (SELECT count(*)
     FROM public.workouts workout
     WHERE (workout.user_id = p_target_user_id
            OR workout.owner_user_id = p_target_user_id)
       AND (
         EXISTS (
           SELECT 1 FROM public.user_workouts assignment
           WHERE assignment.workout_id = workout.id
             AND assignment.user_id <> p_target_user_id
         )
         OR (workout.user_id IS NOT NULL
             AND workout.user_id <> p_target_user_id)
         OR (workout.owner_user_id IS NOT NULL
             AND workout.owner_user_id <> p_target_user_id)
       ))
    +
    (SELECT count(*)
     FROM public.meal_plans plan
     WHERE plan.user_id = p_target_user_id
       AND EXISTS (
         SELECT 1 FROM public.user_meal_plans assignment
         WHERE assignment.meal_plan_id = plan.id
           AND assignment.user_id <> p_target_user_id
       ))
  INTO v_shared_direct_content_count;

  -- Feedback the target authored on another athlete's log cascades away with
  -- the target's profile, so it needs an operator decision before deletion.
  SELECT count(*) INTO v_shared_authored_content_count
  FROM public.workout_feedback feedback
  WHERE feedback.coach_id = p_target_user_id
    AND feedback.user_id <> p_target_user_id;

  INSERT INTO public.user_deletion_jobs (
    id,
    target_user_id,
    requested_by,
    status,
    last_error_code,
    last_error_message
  ) VALUES (
    p_target_user_id,
    p_target_user_id,
    p_requested_by,
    CASE WHEN v_off_prefix_count > 0
           OR v_cross_user_request_count > 0
           OR v_shared_direct_content_count > 0
           OR v_shared_authored_content_count > 0
      THEN 'manual_review' ELSE 'requested' END,
    CASE
      WHEN v_off_prefix_count > 0 THEN 'off_prefix_storage_objects'
      WHEN v_cross_user_request_count > 0 THEN 'retained_generation_request'
      WHEN v_shared_direct_content_count > 0 THEN 'shared_direct_content'
      WHEN v_shared_authored_content_count > 0 THEN 'shared_authored_content'
      ELSE NULL
    END,
    CASE
      WHEN v_off_prefix_count > 0 THEN 'Target owns storage objects outside the supported user prefix.'
      WHEN v_cross_user_request_count > 0 THEN 'Target requested a meal plan for another user.'
      WHEN v_shared_direct_content_count > 0 THEN 'Target directly owns content assigned to another user.'
      WHEN v_shared_authored_content_count > 0 THEN 'Target authored coach feedback on another user''s training log.'
      ELSE NULL
    END
  ) RETURNING * INTO v_job;

  INSERT INTO public.user_deletion_bucket_progress (job_id, bucket_id)
  VALUES
    (v_job.id, 'chat-images'),
    (v_job.id, 'check-in-photos'),
    (v_job.id, 'meal-photos');

  INSERT INTO public.user_deletion_prefix_work (job_id, bucket_id, prefix, depth)
  VALUES
    (v_job.id, 'chat-images', p_target_user_id::text, 0),
    (v_job.id, 'check-in-photos', p_target_user_id::text, 0),
    (v_job.id, 'meal-photos', p_target_user_id::text, 0);

  RETURN v_job;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_claim_user_deletion(
  p_job_id UUID,
  p_lease_seconds INTEGER DEFAULT 60
)
RETURNS public.user_deletion_jobs
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_job public.user_deletion_jobs;
BEGIN
  IF p_lease_seconds < 15 OR p_lease_seconds > 300 THEN
    RAISE EXCEPTION 'Lease must be between 15 and 300 seconds' USING ERRCODE = '22023';
  END IF;

  UPDATE public.user_deletion_jobs
  SET status = CASE
        WHEN status = 'requested' THEN 'cleaning_storage'
        WHEN status = 'retryable_error' THEN COALESCE(resume_status, 'cleaning_storage')
        ELSE status
      END,
      resume_status = NULL,
      lease_token = gen_random_uuid(),
      lease_expires_at = now() + make_interval(secs => p_lease_seconds),
      attempt_count = attempt_count + 1,
      last_error_code = NULL,
      last_error_message = NULL
  WHERE id = p_job_id
    AND status IN ('requested', 'cleaning_storage', 'deleting_auth', 'retryable_error')
    AND (lease_expires_at IS NULL OR lease_expires_at < now())
  RETURNING * INTO v_job;

  RETURN v_job;
END;
$$;

