-- Repeat the ownership/reference preflight immediately before Auth deletion.
-- The first preflight occurs after the profile is blocked; this second check
-- also catches an upload transaction that was already in flight at that time.
CREATE OR REPLACE FUNCTION public.admin_preflight_user_deletion(
  p_job_id UUID,
  p_lease_token UUID
)
RETURNS TABLE (ready BOOLEAN, next_status TEXT, error_code TEXT)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_target_user_id UUID;
  v_off_prefix_count BIGINT;
  v_in_prefix_count BIGINT;
  v_cross_user_request_count BIGINT;
  v_shared_direct_content_count BIGINT;
  v_shared_authored_content_count BIGINT;
  v_error_code TEXT;
  v_error_message TEXT;
BEGIN
  SELECT target_user_id INTO v_target_user_id
  FROM public.user_deletion_jobs
  WHERE id = p_job_id
    AND lease_token = p_lease_token
    AND lease_expires_at >= now()
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Deletion job lease is no longer valid' USING ERRCODE = '40001';
  END IF;

  SELECT count(*) INTO v_off_prefix_count
  FROM storage.objects
  WHERE bucket_id IN ('chat-images', 'check-in-photos', 'meal-photos')
    AND owner_id = v_target_user_id::text
    AND name <> v_target_user_id::text
    AND name NOT LIKE v_target_user_id::text || '/%';

  SELECT count(*) INTO v_in_prefix_count
  FROM storage.objects
  WHERE bucket_id IN ('chat-images', 'check-in-photos', 'meal-photos')
    AND (
      name = v_target_user_id::text
      OR name LIKE v_target_user_id::text || '/%'
    );

  SELECT count(*) INTO v_cross_user_request_count
  FROM public.meal_plan_generation_requests
  WHERE requested_by = v_target_user_id
    AND user_id <> v_target_user_id;

  SELECT
    (SELECT count(*)
     FROM public.workouts workout
     WHERE (workout.user_id = v_target_user_id
            OR workout.owner_user_id = v_target_user_id)
       AND (
         EXISTS (
           SELECT 1 FROM public.user_workouts assignment
           WHERE assignment.workout_id = workout.id
             AND assignment.user_id <> v_target_user_id
         )
         OR (workout.user_id IS NOT NULL
             AND workout.user_id <> v_target_user_id)
         OR (workout.owner_user_id IS NOT NULL
             AND workout.owner_user_id <> v_target_user_id)
       ))
    +
    (SELECT count(*)
     FROM public.meal_plans plan
     WHERE plan.user_id = v_target_user_id
       AND EXISTS (
         SELECT 1 FROM public.user_meal_plans assignment
         WHERE assignment.meal_plan_id = plan.id
           AND assignment.user_id <> v_target_user_id
       ))
  INTO v_shared_direct_content_count;

  SELECT count(*) INTO v_shared_authored_content_count
  FROM public.workout_feedback feedback
  WHERE feedback.coach_id = v_target_user_id
    AND feedback.user_id <> v_target_user_id;

  IF v_off_prefix_count > 0
     OR v_cross_user_request_count > 0
     OR v_shared_direct_content_count > 0
     OR v_shared_authored_content_count > 0 THEN
    v_error_code := CASE
      WHEN v_off_prefix_count > 0 THEN 'off_prefix_storage_objects'
      WHEN v_cross_user_request_count > 0 THEN 'retained_generation_request'
      WHEN v_shared_direct_content_count > 0 THEN 'shared_direct_content'
      WHEN v_shared_authored_content_count > 0 THEN 'shared_authored_content'
      ELSE NULL
    END;
    v_error_message := CASE
      WHEN v_off_prefix_count > 0 THEN 'Target owns storage objects outside the supported user prefix.'
      WHEN v_cross_user_request_count > 0 THEN 'Target requested a meal plan for another user.'
      WHEN v_shared_direct_content_count > 0 THEN 'Target directly owns content assigned to another user.'
      WHEN v_shared_authored_content_count > 0 THEN 'Target authored coach feedback on another user''s training log.'
      ELSE NULL
    END;

    UPDATE public.user_deletion_jobs
    SET status = 'manual_review',
        resume_status = NULL,
        lease_token = NULL,
        lease_expires_at = NULL,
        last_error_code = v_error_code,
        last_error_message = v_error_message
    WHERE id = p_job_id;

    RETURN QUERY SELECT false, 'manual_review'::TEXT, v_error_code;
    RETURN;
  END IF;

  IF v_in_prefix_count > 0 THEN
    UPDATE public.user_deletion_bucket_progress
    SET status = 'pending', updated_at = now()
    WHERE job_id = p_job_id;

    UPDATE public.user_deletion_prefix_work
    SET status = 'pending', updated_at = now()
    WHERE job_id = p_job_id;

    INSERT INTO public.user_deletion_prefix_work (
      job_id, bucket_id, prefix, depth, status
    )
    SELECT p_job_id, bucket_id, v_target_user_id::TEXT, 0, 'pending'
    FROM public.user_deletion_bucket_progress
    WHERE job_id = p_job_id
    ON CONFLICT (job_id, bucket_id, prefix)
    DO UPDATE SET status = 'pending', updated_at = now();

    UPDATE public.user_deletion_jobs
    SET status = 'cleaning_storage',
        resume_status = NULL,
        lease_token = NULL,
        lease_expires_at = NULL,
        last_error_code = 'in_prefix_storage_objects',
        last_error_message = 'Storage changed during deletion; cleanup must run again.'
    WHERE id = p_job_id;

    RETURN QUERY SELECT false, 'cleaning_storage'::TEXT, 'in_prefix_storage_objects'::TEXT;
    RETURN;
  END IF;

  RETURN QUERY SELECT true, 'deleting_auth'::TEXT, NULL::TEXT;
END;
$$;

-- Explicit operator recheck for a manual-review job. Calling this RPC does not
-- bypass either safety condition; it only resumes after the operator has
-- resolved the offending object/reference. The Edge handler records the
-- associated attempt and terminal audit event with the operator request id.
CREATE OR REPLACE FUNCTION public.admin_recheck_user_deletion_manual_review(
  p_job_id UUID
)
RETURNS public.user_deletion_jobs
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_job public.user_deletion_jobs;
  v_off_prefix_count BIGINT;
  v_cross_user_request_count BIGINT;
  v_shared_direct_content_count BIGINT;
  v_shared_authored_content_count BIGINT;
BEGIN
  SELECT * INTO v_job
  FROM public.user_deletion_jobs
  WHERE id = p_job_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Deletion job not found' USING ERRCODE = 'P0002';
  END IF;
  IF v_job.status <> 'manual_review' THEN
    RETURN v_job;
  END IF;

  SELECT count(*) INTO v_off_prefix_count
  FROM storage.objects
  WHERE bucket_id IN ('chat-images', 'check-in-photos', 'meal-photos')
    AND owner_id = v_job.target_user_id::text
    AND name <> v_job.target_user_id::text
    AND name NOT LIKE v_job.target_user_id::text || '/%';

  SELECT count(*) INTO v_cross_user_request_count
  FROM public.meal_plan_generation_requests
  WHERE requested_by = v_job.target_user_id
    AND user_id <> v_job.target_user_id;

  SELECT
    (SELECT count(*)
     FROM public.workouts workout
     WHERE (workout.user_id = v_job.target_user_id
            OR workout.owner_user_id = v_job.target_user_id)
       AND (
         EXISTS (
           SELECT 1 FROM public.user_workouts assignment
           WHERE assignment.workout_id = workout.id
             AND assignment.user_id <> v_job.target_user_id
         )
         OR (workout.user_id IS NOT NULL
             AND workout.user_id <> v_job.target_user_id)
         OR (workout.owner_user_id IS NOT NULL
             AND workout.owner_user_id <> v_job.target_user_id)
       ))
    +
    (SELECT count(*)
     FROM public.meal_plans plan
     WHERE plan.user_id = v_job.target_user_id
       AND EXISTS (
         SELECT 1 FROM public.user_meal_plans assignment
         WHERE assignment.meal_plan_id = plan.id
           AND assignment.user_id <> v_job.target_user_id
       ))
  INTO v_shared_direct_content_count;

  SELECT count(*) INTO v_shared_authored_content_count
  FROM public.workout_feedback feedback
  WHERE feedback.coach_id = v_job.target_user_id
    AND feedback.user_id <> v_job.target_user_id;

  IF v_off_prefix_count = 0
     AND v_cross_user_request_count = 0
     AND v_shared_direct_content_count = 0
     AND v_shared_authored_content_count = 0 THEN
    UPDATE public.user_deletion_jobs
    SET status = 'cleaning_storage',
        resume_status = NULL,
        lease_token = NULL,
        lease_expires_at = NULL,
        last_error_code = NULL,
        last_error_message = NULL
    WHERE id = p_job_id
    RETURNING * INTO v_job;
    RETURN v_job;
  END IF;

  UPDATE public.user_deletion_jobs
  SET last_error_code = CASE
        WHEN v_off_prefix_count > 0 THEN 'off_prefix_storage_objects'
        WHEN v_cross_user_request_count > 0 THEN 'retained_generation_request'
        WHEN v_shared_direct_content_count > 0 THEN 'shared_direct_content'
        WHEN v_shared_authored_content_count > 0 THEN 'shared_authored_content'
        ELSE NULL
      END,
      last_error_message = CASE
        WHEN v_off_prefix_count > 0 THEN 'Target owns storage objects outside the supported user prefix.'
        WHEN v_cross_user_request_count > 0 THEN 'Target requested a meal plan for another user.'
        WHEN v_shared_direct_content_count > 0 THEN 'Target directly owns content assigned to another user.'
        WHEN v_shared_authored_content_count > 0 THEN 'Target authored coach feedback on another user''s training log.'
        ELSE NULL
      END
  WHERE id = p_job_id
  RETURNING * INTO v_job;

  RETURN v_job;
END;
$$;

